/* Writes peak-power/js/data/site-grades.js: the Find a site county grades, a few key facts per county, and the Prototype's own cost and carbon
   figures for a late grid connection, so the Data Center Climate Explorer can show the SAME numbers without a second copy of the scoring rules.

   How: it opens the real Prototype in headless Chrome/Edge and reads what the Prototype itself computed (cOverall(c) and c.r for all 3,142 counties,
   the state policy table, the layer descriptions) and runs the Prototype's own engine for the delay cases. Nothing is re-implemented, so the two pages
   cannot disagree unless this file is stale; tests/e2e/site-overlay.e2e.mjs fails if it is. Re-run after any change to the grading code or the
   engine inputs in js/prototype.js:

       node scripts/build_site_grades.mjs

   Needs Node 22+ and Chrome or Edge (set CHROME_PATH if it is not found), like the other browser tests. Takes about a minute. */
import fs from 'node:fs';
import path from 'node:path';
import { launch, openPage, BASE, ROOT } from '../tests/e2e/lib.mjs';

const OUT = path.join(ROOT, 'peak-power', 'js', 'data', 'site-grades.js');
const DELAYS = [0, 6, 12];   // months the grid connection is late; 12 is the Prototype's own "Greenfield" project
const b = await launch();
try {
  const p = await openPage(b, { url: BASE + 'prototype.html' });
  const ready = await p.waitFor("!!window.PEAKPOWER_PROTOTYPE_API && PEAKPOWER_PROTOTYPE_API.MAPD.c.length>3000 && PEAKPOWER_PROTOTYPE_API.MAPD.c.every(c=>c.r.length>=8)", 60000);
  if (!ready) throw new Error('The Prototype did not finish loading its county grades');
  const data = JSON.parse(await p.ev(`(() => { const {cOverall, GL, LAYTXT, STP, MAPD} = PEAKPOWER_PROTOTYPE_API; return JSON.stringify({
    labels: GL,
    order: ['all','loc','en','pol','fib','water','haz','zon','pwr'],
    layers: LAYTXT,
    states: Object.fromEntries(Object.entries(STP).map(([k,v]) => [k, {a: v.a, n: v.n, reg: v.reg, g: v.g, t: v.t}])),
    metros: MAPD.metros,
    qreg: MAPD.qreg.map(g => ({name: g.name, med: g.med, p25: g.p25, p75: g.p75, n: g.n, act: g.act})),
    g: Object.fromEntries(MAPD.c.map(c => [c.f, String(cOverall(c)) + c.r.slice(0,8).join('')])),
    // per county: name, miles to metro, metro index, miles to nearest network facility (or null), water withdrawn % (null none, -1 arid), hazard percentile (or null), queue region index (or null), ERCOT zone (Texas only)
    k: Object.fromEntries(MAPD.c.map(c => [c.f, [c.n, c.dm, c.am, c.fd == null ? null : c.fd, c.w == null ? null : (c.w < 0 ? -1 : c.wp), c.h == null ? null : c.h[0], c.q == null ? null : c.q, c.s === '48' ? c.z : null]]))
  }); })()`));
  // every county: one overall digit + eight factor digits (0 Good, 1 Moderate, 2 Bad, 3 Not graded, 4 Excellent)
  for (const [f, s] of Object.entries(data.g)) if (!/^[0-4][0-4]{8}$/.test(s)) throw new Error('Unexpected grade string for ' + f + ': ' + s);

  // The Prototype's engine, run for the packet's Williamson County case with the grid connection N months late (acres fixed at the packet's 8).
  // This is the same call the Prototype makes for each project card: best opening month by 10-year profit among plans that pass the reliability test.
  const delay = [];
  for (const months of DELAYS) {
    const r = JSON.parse(await p.ev(`JSON.stringify(PEAKPOWER_PROTOTYPE_API.delayCase(${months}))`));
    if (!r) throw new Error('No plan passes the reliability test with a ' + months + ' month delay');
    delay.push({ months, ...r });
  }
  for (const d of delay) for (const k of ['open', 'total', 'perMWh', 'kg', 'clean', 'profit']) if (typeof d[k] !== 'number' || !isFinite(d[k])) throw new Error('Bad delay result ' + JSON.stringify(d));

  const body = '/* Generated by scripts/build_site_grades.mjs from the Prototype\'s own grading code and engine. Do not edit by hand.\n' +
    '   g[fips] = 9 digits: Overall, then Location, Energy, Policy, Fiber, Water, Hazard, Zoning, Time to power.\n' +
    '   Grade digits: 0 Good, 1 Moderate, 2 Bad, 3 Not graded, 4 Excellent (labels below).\n' +
    '   k[fips] = [county, miles to metro, metro index, miles to nearest network facility, water withdrawn % (-1 arid), hazard percentile, queue region index, ERCOT zone].\n' +
    '   delay = the Prototype engine\'s best plan for the packet case with the grid connection N months late (open = initial service month; total = 10-year power cost in $; kg = kg CO2/MWh). */\n' +
    'window.PEAKPOWER_SITE_GRADES=' + JSON.stringify({ v: 2, ...data, delay }) + ';\n';
  fs.writeFileSync(OUT, body);
  console.log('wrote', path.relative(ROOT, OUT), (body.length / 1024).toFixed(0) + ' KB,', Object.keys(data.g).length, 'counties,', Object.keys(data.states).length, 'states');
  for (const d of delay) console.log('  delay', d.months, 'months: open month', d.open, '| $' + (d.total / 1e6).toFixed(1) + 'M | $' + d.perMWh.toFixed(1) + '/MWh |', d.kg.toFixed(0), 'kg/MWh | clean', (100 * d.clean).toFixed(0) + '%');
} finally { b.close(); }
process.exit(0);
