#!/usr/bin/env python3
"""Refresh the resource catalogue in the browser's reference data from the symposium packet.

    python scripts/build_reference_data.py            # from the repository root

Reads the packet's resource_options.csv and reference_hourly.csv and rewrites the `res` (catalogue) block and the hourly series of
peak-power/js/data/reference-data.js. The flag series (stress hours, events, calendar) are kept but must still match the packet.

Nothing is typed by hand: every catalogue value (prices, CAPEX, maximum MW, land per MW ...) comes from the packet file.
Standard library only; the output is deterministic.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKET = ROOT / "data" / "Symposium_Packet" / "data"
TARGET = ROOT / "peak-power" / "js" / "data" / "reference-data.js"
HEADER = ("/* Benchmark reference year and resource catalogue from the symposium packet (v6.0.1, V2).\n"
          "   Shape: { ref: {...hourly series, prices, grid...}, res: {...resource offers} }.\n"
          "   The catalogue is generated by scripts/build_reference_data.py from data/Symposium_Packet/data/resource_options.csv. */\n")
NUMERIC = ["block_mw", "max_mw", "available_month", "capex_usd_per_kw", "fom_usd_per_kw_year", "life_years", "payment_usd_per_mwh",
           "heat_rate_mmbtu_per_mwh_hhv", "co2_t_per_mwh", "clean_credit", "duration_hours", "round_trip_efficiency",
           "max_cycles_per_year", "land_acres_per_mw"]
TEXT = ["kind", "location", "payment_basis"]


def num(text: str):
    v = float(text)
    return int(v) if v.is_integer() and "." not in text else v


def main() -> int:
    text = TARGET.read_text(encoding="utf-8")
    start = text.index("= {") + 2
    data = json.loads(text[start:text.rindex("}") + 1])

    # Hourly series: rebuilt from the packet's reference_hourly.csv at 9 decimals, so the browser engine uses the packet's values
    # (the official checker's tolerance is 1e-5 MW; 4 to 5 decimals is not enough). The integer flag series must still agree.
    with open(PACKET / "reference_hourly.csv", newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    ref = data["ref"]
    if len(rows) != len(ref["stress"]) or any(int(r["stress_active"]) != v for r, v in zip(rows, ref["stress"])):
        print("STOP: the stress hours in reference-data.js do not match reference_hourly.csv; rebuild `ref` (flags, events, calendar) first.", file=sys.stderr)
        return 1
    series = {"wind": "wind_proxy_cf", "solar": "solar_proxy_cf", "price": "wholesale_price_usd_per_mwh", "hh": "henry_hub_usd_per_mmbtu",
              "load": "load_mw", "t1": "tier1_relocatable_mw", "t2": "tier2_interruptible_mw"}
    widest = 0.0
    for key, col in series.items():
        fresh = [round(float(r[col]), 9) for r in rows]
        widest = max(widest, max(abs(a - b) for a, b in zip(fresh, ref[key])))
        ref[key] = fresh
    for key, col, scale in (("grid_adder", "grid_adder_usd_per_mwh", None), ("gas_adder", "delivered_gas_adder_usd_per_mmbtu", None), ("grid_co2", "grid_co2_t_per_mwh", None)):
        ref[key] = round(float(rows[0][col]), 9) if key == "grid_co2" else num(rows[0][col])

    res = {}
    with open(PACKET / "resource_options.csv", newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            entry = {k: row[k] for k in TEXT}
            for k in NUMERIC:
                entry[k] = num(row[k])
            res[row["option_id"]] = entry

    changed = [k for k in res if k in data["res"] and any(data["res"][k].get(f) != res[k][f] for f in res[k] if f in data["res"][k])]
    data["res"] = res
    out = HEADER + "window.PEAKPOWER_REFERENCE = " + json.dumps(data, separators=(",", ":")) + ";\n"
    TARGET.write_text(out, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}: {len(res)} resources (values changed for {', '.join(changed) or 'none'}); hourly series refreshed, largest change {widest:.2g}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
